    const ctx = document.getElementById("healthGauge");

    if (!ctx) return;

    new Chart(ctx, {

        type: 'doughnut',

        data: {

            labels: ['Healthy', 'Remaining'],

            datasets: [{
                data: [96, 4],
                backgroundColor: [
                    '#22c55e',
                    '#e9ecef'
                ],
                borderWidth: 0,
                hoverOffset: 2
            }]

        },

        options: {

            responsive: true,
            maintainAspectRatio: false,

            cutout: '75%',

            plugins: {

                legend: {
                    display: false
                },

                tooltip: {
                    enabled: true
                }

            }

        },

        plugins: [{

            id: 'centerText',

            afterDraw(chart) {

                const {
                    ctx
                } = chart;

                const meta = chart.getDatasetMeta(0).data[0];

                ctx.save();

                ctx.font = "bold 32px Arial";
                ctx.fillStyle = "#198754";
                ctx.textAlign = "center";
                ctx.textBaseline = "middle";
                ctx.fillText("96%", meta.x, meta.y - 8);

                ctx.font = "14px Arial";
                ctx.fillStyle = "#6c757d";
                ctx.fillText("Health", meta.x, meta.y + 20);

                ctx.restore();

            }

        }]

    });

});
</script>

</script>
@stack('scripts')

     </body>



     </html>